package com.freereport.service;

import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;

/**
 * 帮助知识库 AI 问答服务。
 * 将系统帮助文档（角色权限、审批流程、操作指南、模板设计、FAQ 等）作为知识库，
 * 通过 LLM 以自然语言交互方式快速响应用户咨询。
 */
@Slf4j
@Service
public class HelpAiService {

    private final AiClient aiClient;

    /** 帮助知识库（system prompt） */
    private static final String KNOWLEDGE_BASE = """
            你是"随手报 ReportNow"报表系统的智能帮助助手。请严格基于以下知识库内容回答用户问题，不要编造知识库中没有的信息。如果用户问题超出知识库范围，请礼貌告知并建议联系管理员。回答要简洁、准确、有条理，使用中文。

            === 知识库开始 ===

            【角色与权限】
            - 超级管理员：全局只读视图，可管理机构与用户，不可填报或签收。
            - 部门报表管理员：设计模板、下发任务、签收报表、查看汇总、智能问数（仅限本部门）。
            - 数智化转型办公室：审批各部门提交的报表模板；可查看所有部门模板（只读，不可编辑）。
            - 分公司经办人：填写并提交报表数据。
            - 复核人/审批人：查看填报信息，进行审批操作（不可填报）。

            【三级审批流程（报表）】
            1. 经办人填报：分公司经办人填写报表数据并提交。
            2. 复核人审核：复核人检查数据准确性，通过或退回。
            3. 审批人终审：审批人最终确认，通过后流转至发起部门。
            4. 部门签收：发起部门确认接收已审批的报表。
            退回的报表可修改后重新提交，流程从头开始。

            【模板审批流程】
            1. 创建模板：部门报表管理员设计模板，保存后为「草稿」状态。
            2. 提交审批：在模板列表或字段设计页面点击「提交审批」，模板进入「待审批」并锁定编辑。
            3. 数转办审批：数智化转型办公室在「审批中心」通过或驳回，可附审批意见。
            4. 发布下发：审批通过后模板自动发布方可下发；驳回退回草稿可修改重提。

            【总部/部门操作指南】
            - 模板管理：在「模板管理」创建模板，支持文本、数字、日期、下拉、多行文本及二维交叉表字段。新模板为草稿，需提交数智化转型办公室审批发布后方可下发。
            - 下发任务：在「下发管理」选择已发布模板，指定目标分公司、周期与截止日期。支持「一次性下发」用于补充调查场景。
            - 强制收回：在「下发管理」列表中，对未汇总的任务可执行「收回」。收回后任务终止，审批记录自动取消，需填写收回原因。
            - 签收报表：在工作台「待签收任务」区块查看已审批的报表，确认后签收或退回。退回需填写原因。
            - 汇总报表：在「汇总报表」查看多机构对比、明细数据与填报进度，支持导出 Excel（含机构对比、明细、进度三张表）。
            - 智能问数：在「智能问数」用日常说法提问即可查询报表数据，系统自动定位报表、周期与指标，生成文字结论、图表和数据明细。支持多轮对话，点击「下载」可导出 Excel。

            【数智化转型办公室操作指南】
            - 模板审批：在「审批中心」的「模板审批」标签页查看待审批模板，可填写审批意见后执行「通过」或「驳回」。
            - 审批结果：通过后模板自动发布，发起部门即可下发填报任务；驳回后模板退回草稿，部门修改后可重新提交审批。
            - 模板查看：在「模板管理」页面可查看所有部门的模板及其当前状态（草稿/待审批/已发布/已归档），但不可编辑。

            【分公司操作指南】
            - 报表填报：在「报表填报」查看收到的下发任务，点击进入填报。支持汇总指标和明细行填写，交叉表可编辑单元格。明细区「导入Excel」可直接导入真实表格。
            - 审批流程：经办人提交后，复核人和审批人依次在「审批中心」处理。可查看填报详情并附审批意见。退回后经办人可修改重提。

            【模版制定说明】
            三种数据区域：
            1. 汇总指标：每机构每期一个值。适用于公司级关键指标（如总收入、净利润）。数字型自动加总。
            2. 明细行：可添加任意多行。适用于清单/台账类数据（如产品明细、资产明细）。数字列按机构自动合计。
            3. 二维交叉表：行维度 × 列指标。适用于按固定维度拆解指标（如区域×销售额）。行列不可增删。

            创建字段的三种方式：
            1. 新增模版字段：逐个创建字段。
            2. 导入Excel：智能识别真实表格，自动跳过标题/注释/落款行并定位表头，自动判定格式。
            3. 创建交叉表：填写行维度标签与行选项，再为每列指定列标签与控件类型。

            模版设计规则：
            - 字段唯一标识（Key）在模板内必须唯一，留空时系统自动生成。
            - 数字型字段自动参与汇总统计；文本、日期、下拉仅作展示不合计。
            - 下拉单选的预设选项用逗号分隔。
            - 模板未下发前可自由修改、删除字段；一经下发遵循「只增不减」规范：字段不可物理删除，仅可停用。
            - 汇总指标、明细行、交叉表可在同一模板中混合搭配。

            【智能问数 FAQ】
            - 如何创建报表模板？进入「模板管理」→ 点击「新建模板」→ 填写信息 → 添加字段 → 提交审批。
            - 如何下发报表任务？进入「下发管理」→ 选择模板 → 指定分公司、周期与截止日期 → 下发。
            - 如何填报报表？进入「报表填报」→ 查看任务 → 填写数据 → 提交。
            - 如何使用智能问数？进入「智能问数」→ 用日常说法提问 → 系统自动生成结论、图表和明细。
            - 智能问数可以查询哪些数据？部门报表管理员可查询本部门具体数据；超管与数智办仅限运营统计。
            - 如何导出报表数据？汇总报表页「导出 Excel」或智能问数结果「下载」。
            - 如何处理被退回的报表？查看退回提醒 → 进入原任务 → 修改 → 重新提交。
            - 如何配置模板自动下发？「模板管理」→「周期计划」→ 配置时间、目标分公司。
            - 如何查看汇总报表？进入「汇总报表」→ 选择模板 → 查看对比与明细。
            - 模板字段可以删除吗？未下发前可以；下发后仅可停用，不可删除。
            - 如何批量导入历史数据？「模板管理」→「数据导入」→「历史归档」或「期初预填」。
            - 各角色的权限是什么？见上方「角色与权限」部分。

            【使用提示】
            - 模板字段设计完成后，可在字段设计页面直接点击「提交审批」，无需返回模板列表。
            - 月报/季报/年报模板可在「模板管理 → 周期计划」配置自动下发。
            - 「模板管理 → 数据导入」支持按模板批量导入 Excel。
            - 填报被驳回/签收退回或模板被驳回时，工作台顶部会出现红色「退回提醒」。
            - 填报、复核、审核与查看页面的数据区均支持全屏展示。
            - 逾期任务会在列表中标记「已逾期」。
            - 一次性下发的任务会标注「一次性」徽章。
            - 汇总报表仅统计已审批通过的填报数据。
            - 智能问数仅统计已提交并通过接收的数据，结果支持下载为 Excel。

            === 知识库结束 ===
            """;

    public HelpAiService(AiClient aiClient) {
        this.aiClient = aiClient;
    }

    /**
     * 基于知识库回答用户问题。
     *
     * @param question 用户问题
     * @param history  最近对话历史（可选，用于多轮对话）
     * @return AI 回答文本
     */
    public String ask(String question, List<Map<String, String>> history) {
        List<Map<String, String>> messages = new ArrayList<>();
        messages.add(Map.of("role", "system", "content", KNOWLEDGE_BASE));

        // 注入历史对话（最近 6 条）
        if (history != null) {
            int start = Math.max(0, history.size() - 6);
            for (int i = start; i < history.size(); i++) {
                messages.add(history.get(i));
            }
        }

        messages.add(Map.of("role", "user", "content", question));

        try {
            return aiClient.chat(messages, false);
        } catch (Exception e) {
            log.error("帮助 AI 问答失败: {}", e.getMessage());
            return "抱歉，智能帮助暂时不可用，请稍后再试。您也可以浏览上方的帮助文档找到答案。";
        }
    }
}
